_EN = [re.compile(p) for p in EN_PATTERNS]
_ZH = [re.compile(p) for p in ZH_PATTERNS]


def _name_patterns(names: Iterable[str]) -> list[re.Pattern]:
    out = []
    for raw in names:
        if not isinstance(raw, str) or not raw.strip():
            continue
        full = normalize(raw)
        variants = {full} | {p for p in full.split(" ") if len(p) >= 2}
        for v in sorted(variants, key=len, reverse=True):
            n = re.escape(v)
            out += [re.compile(rf"\b(?:{SELF}|{YOU}|you|name is|call me|speak as|speaking as|introduce yourself as|sign as)\s+"
                               rf"(?:\w+\s+){{0,1}}?{n}\b(?!'s|’s)"),
                    re.compile(rf"\b{n}\b(?!'s)\s*(?:,\s*)?(?:speaking|here|calling|on the line|is calling)\b"),
                    re.compile(rf"\b(?:be|become|pose as|act as)\s+{n}\b(?!'s)")]
            cjk = v.replace(" ", "")
            out += [re.compile(rf"我(?:就|也|确实|真的|其实)?(?:是|叫)(?:一个|个)?{re.escape(cjk)}(?!的)"),
                    re.compile(rf"{re.escape(cjk)}本人"),
                    re.compile(rf"(?:说|称|声称|假装|冒充)(?:你|自己|我)?(?:是|就是){re.escape(cjk)}(?!的)")]
    return out


def validate_script(text: str, names: Iterable[str] = ()) -> None:
    """Backstop deny-list over normalized text. ``names`` are the user's and account holder's names: any
    first-person or second-person claim to be them is rejected."""
    if not isinstance(text, str) or not text.strip():
        raise CallPolicyError("call script is empty")
    norm, cjk = normalize(text), _cjk(text)
    for sentence in re.split(r"(?<=[.!?;\n])\s+|[。！？；\n]", norm):
        for rx in _EN:
            m = rx.search(sentence)
            if m:
                raise CallPolicyError(f"call script makes a forbidden identity claim or evasion: {m.group(0)!r}")
    for rx in _ZH:
        m = rx.search(cjk)
        if m:
            raise CallPolicyError(f"call script makes a forbidden identity claim or evasion: {m.group(0)!r}")
    for rx in _name_patterns(names):
        m = rx.search(norm) or rx.search(cjk)
        if m:
            raise CallPolicyError(f"call script impersonates the user: {m.group(0)!r}")


# -- allowlist structure -------------------------------------------------------------------
IDENTITY_TOPIC = re.compile(
    rf"\b(?:{AI}|human\w*|person|persons|real one|identity|who you are|who is calling|"
    r"pretend\w*|impersonat\w*|disclos\w* (?:that|what) you|are you (?:a|an|real))\b")
IDENTITY_TOPIC_ZH = re.compile(r"(?<![a-z])ai(?![a-z])|人工智能|机器人|机器|真人|人类|本人|身份|录音|自动|假装|冒充|扮演|是不是人|是人吗")


def validate_task_step(step: str, names: Iterable[str] = ()) -> None:
    """A task step may not discuss identity at all; the generated identity block alone covers who is calling."""
    if not isinstance(step, str) or not step.strip():
        raise CallPolicyError("task step is empty")
    norm, cjk = normalize(step), _cjk(step)
    m = IDENTITY_TOPIC.search(norm) or IDENTITY_TOPIC_ZH.search(cjk)
    if m:
        raise CallPolicyError(f"task steps may not talk about the caller's identity ({m.group(0)!r}); "
                              "the generated identity rules handle that")
    validate_script(step, names)


def _identity_block(user_name: str, policy: CallPolicy, lang: str) -> list[str]:
    opening = OPENING[lang][policy.proactive_ai_disclosure].format(user_name=user_name)
    truthful = TRUTHFUL_ANSWER[lang].format(user_name=user_name)
    volunteer = VOLUNTEER[lang][policy.proactive_ai_disclosure]
    return [r.format(opening=opening, truthful=truthful, volunteer=volunteer, user_name=user_name)
            for r in RULES[lang]]


def _check_name(user_name: Any) -> str:
    if not isinstance(user_name, str) or not user_name.strip() or len(user_name) > 80 or \
            re.search(r"[\n\[\]{}\"「」]", user_name):
        raise CallPolicyError("call_user_name must be the user's name (one line, no brackets or quotes)")
    return user_name.strip()


def build_call_instructions(user_name: str, policy: CallPolicy | None = None, lang: str = "en") -> dict[str, Any]:
    """Opening line + the honesty rules that go at the top of every call prompt/pathway."""
    policy = policy or load_policy()
    lang = lang if lang in OPENING else "en"
    user_name = _check_name(user_name)
    return {"opening": OPENING[lang][policy.proactive_ai_disclosure].format(user_name=user_name),
            "truthful_answer": TRUTHFUL_ANSWER[lang].format(user_name=user_name),
            "rules": _identity_block(user_name, policy, lang),
            "proactive_ai_disclosure": policy.proactive_ai_disclosure, "truthful_if_asked": True}


def build_call_script(user_name: str, task_steps: list[str], policy: CallPolicy | None = None, lang: str = "en",
                      account_holder_name: str | None = None) -> str:
    """The only supported way to write a call script: generated identity block + checked task steps."""
    policy = policy or load_policy()
    lang = lang if lang in OPENING else "en"
    user_name = _check_name(user_name)
    if not isinstance(task_steps, list) or not task_steps:
        raise CallPolicyError("a call script needs at least one task step")
    names = [user_name] + ([account_holder_name] if account_holder_name else [])
    steps = []
    for s in task_steps:
        if not isinstance(s, str) or "\n" in s.strip():
            raise CallPolicyError("each task step must be one line")
        validate_task_step(s, names)
        steps.append(s.strip())
    lines = [RULES_HEADER] + [f"- {r}" for r in _identity_block(user_name, policy, lang)] + [TASK_HEADER]
    lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)]
    return "\n".join(lines)


def validate_call_draft(draft: Any, user_name: Any, account_holder_name: str | None = None,
                        policy: CallPolicy | None = None) -> dict[str, Any]:
    """Fail-closed check of a stored call script: exact generated identity block, then identity-free task steps."""
    if not isinstance(draft, str) or not draft.strip():
        raise CallPolicyError("call script is empty")
    policy = policy or load_policy()
    user_name = _check_name(user_name)
    names = [user_name] + ([account_holder_name] if isinstance(account_holder_name, str) and account_holder_name.strip() else [])
    lines = draft.strip().split("\n")
    if TASK_HEADER not in lines:
        raise CallPolicyError(f"call script must be built with build_call_script (missing {TASK_HEADER})")
    head, tail = lines[: lines.index(TASK_HEADER)], lines[lines.index(TASK_HEADER) + 1:]
    expected = {lang: [RULES_HEADER] + [f"- {r}" for r in _identity_block(user_name, policy, lang)] for lang in RULES}
    lang = next((k for k, v in expected.items() if head == v), None)
    if lang is None:
        raise CallPolicyError("the identity rules block was edited or does not match call_user_name; "
                              "rebuild the script with build_call_script")
    if not tail:
        raise CallPolicyError("a call script needs at least one task step")
    steps = []
    for i, line in enumerate(tail, 1):
        m = re.fullmatch(rf"{i}\. (.+)", line)
        if not m:
            raise CallPolicyError(f"task line {i} must be '{i}. <step>'")
        validate_task_step(m.group(1), names)
        steps.append(m.group(1))
    return {"lang": lang, "task_steps": steps}
