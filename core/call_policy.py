"""Call honesty policy (Q3, decided by Charles 2026-10-22; D30).

* Calls do NOT proactively say they are an AI (configurable, off by default).
* If the other party directly asks whether they are talking to an AI, the answer is always truthful: yes, an AI
  assistant calling on behalf of the user. The caller never claims to be human and never claims to be the user.
  This half is not configurable: a policy that tries to change it fails to load.

Call scripts are structured (allowlist first, D30):

    [CALL IDENTITY RULES]      <- generated by build_call_script, must match exactly; covers who is calling
    - ...
    [TASK]                     <- free text, one numbered step per line; may not talk about identity at all
    1. ...

``validate_call_draft`` rebuilds the identity block for the request's ``call_user_name`` and requires an exact
match, then checks every task step: identity topics (AI, bot, human, person, the user's name in a self-claim,
pretending, evading) are rejected outright, and a normalized deny-list (``validate_script``) is applied as a
backstop. The action gate runs this for every ``bland_call`` request on create, amend, and before execution, and
fails closed. This module places no calls.
"""
